// Authentic Discord Bitwise User Flags Decoder (Zero fake badges)
export function parseDiscordBadges(publicFlags: number = 0): Array<{ id: string; name: string; icon: string }> {
  const badges: Array<{ id: string; name: string; icon: string }> = [];

  if (publicFlags & (1 << 0)) {
    badges.push({ id: 'staff', name: 'Discord 員工 (Staff)', icon: DISCORD_OFFICIAL_BADGES.quest });
  }
  if (publicFlags & (1 << 1)) {
    badges.push({ id: 'partner', name: '合作夥伴伺服器擁有者', icon: DISCORD_OFFICIAL_BADGES.quest });
  }
  if (publicFlags & (1 << 2)) {
    badges.push({ id: 'hypesquad_events', name: 'HypeSquad 活動協調員', icon: DISCORD_OFFICIAL_BADGES.hypesquadBravery });
  }
  if (publicFlags & (1 << 3)) {
    badges.push({ id: 'bug_hunter_1', name: '抓蟲達人等級 1', icon: DISCORD_OFFICIAL_BADGES.quest });
  }
  if (publicFlags & (1 << 6)) {
    badges.push({ id: 'bravery', name: 'HypeSquad 勇氣分會 (Bravery)', icon: DISCORD_OFFICIAL_BADGES.hypesquadBravery });
  }
  if (publicFlags & (1 << 7)) {
    badges.push({ id: 'brilliance', name: 'HypeSquad 卓越分會 (Brilliance)', icon: DISCORD_OFFICIAL_BADGES.hypesquadBrilliance });
  }
  if (publicFlags & (1 << 8)) {
    badges.push({ id: 'balance', name: 'HypeSquad 平衡分會 (Balance)', icon: DISCORD_OFFICIAL_BADGES.hypesquadBalance });
  }
  if (publicFlags & (1 << 9)) {
    badges.push({ id: 'early_supporter', name: '早期支持者 (Early Supporter)', icon: DISCORD_OFFICIAL_BADGES.quest });
  }
  if (publicFlags & (1 << 17)) {
    badges.push({ id: 'verified_dev', name: '早期認證機器人開發者', icon: DISCORD_OFFICIAL_BADGES.activeDeveloper });
  }
  if (publicFlags & (1 << 22)) {
    badges.push({ id: 'active_dev', name: '活躍開發者 (Active Developer)', icon: DISCORD_OFFICIAL_BADGES.activeDeveloper });
  }

  return badges;
}

